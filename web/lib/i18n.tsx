const I18n = createContext<{
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
} | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  useEffect(() => {
    localStorage.removeItem("bm-lang");
    document.documentElement.lang = "en";
  }, []);

  const t = (key: string) => en[key] || key;
  return <I18n.Provider value={{ lang: "en", setLang: () => {}, t }}>{children}</I18n.Provider>;
}

export function useI18n() {
  return useContext(I18n) ?? {
    lang: "en" as Lang,
    setLang: () => {},
    t: (key: string) => en[key] || key,
  };
}

export function statusText(status: string, t: (key: string) => string) {
  if (status === "Yeni") return t("status.new");
  if (status === "İcrada") return t("status.progress");
  if (status === "Ödəniş gözlənilir") return t("status.awaiting");
  if (status === "Tamamlandı") return t("status.done");
  if (status === "Ləğv edildi") return t("status.cancelled");
  return status;
}

